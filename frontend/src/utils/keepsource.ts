// 「软链接合并之后数据在哪儿、怎么拿回来」的**唯一判据与文案方**（M290 / M297，2026-09-27 实施批）。
//
// 为什么要有这个文件：M79 裁定"判据归后端、文案归前端"，但那只覆盖了 `undoable === false`
// 的徽标。软链接合并是第三种形状——后端记账说它**可撤**（`undoable=true`），真机却证明
// 那条腿走不到：合并成功即无条件删掉合并前的备份 `.fdd-old`，而回撤以"备份必须在"为硬前提
// （04 §6.50 一 W3-5 读数：点「回撤」交回「找不到合并前的原始备份 …，无法回撤」）。
// 改前这句假承诺在 `RecordsView.vue` 里写了**三份**（悬空行 title、行内回撤 title、
// 批量回撤 title），三份措辞各自漂移——正是 M79 要避免的形状。这里收成一份，视图只引用。
//
// ★ 边界（不许读大）：本文件只决定**界面对用户承诺什么**，不改后端行为——
//   备份生命周期与 `undoSymlink` 一字未动（用户裁定：改文案 + 给直达出口，不改生命周期）。
//   所以"备份恰好残留"那种非设计路径仍由后端的批量回撤处理；界面这一侧不再把它说成常规能力。

/** 记录 kinds 里"软链接合并"那一项（与 OP_KIND_LABEL 的后端 kind 逐字相同）。 */
export const SYMLINK_KIND = 'symlink'

/** 可见文案：替掉原先「可回撤」那一格（用户裁定的原话）。 */
export const KEEP_SOURCE_LABEL = '数据在保留源，需手动放回'

/** 上面那句可见文案的悬浮说明——说清"为什么这一行没有回撤按钮"。 */
export function keepSourceTitle(): string {
  return '软链接合并只在磁盘上留一份数据（保留源）。合并成功后应用会立刻删掉合并前的备份文件，' +
    '所以这条记录没有可回撤的东西，界面上也就不摆「回撤」按钮。\n' +
    '数据没有丢：展开「明细」，点该行的「直达保留原目录」打开保留源所在文件夹，把文件复制回原位置即可。'
}

/**
 * 「直达保留原目录」按钮的悬浮说明。
 *
 * 为什么明写"应用不代劳"：自动把保留源复制回原位，会覆盖用户之后放进那个位置的**同名
 * 第三方文件**——那正是 `verifySymlinked` 那道防线拦的形状（M291/M290）。放回是用户
 * 能看见后果的动作，不是应用能替用户猜的动作。
 */
export function revealKeepTitle(path: string): string {
  return `打开保留源所在的文件夹：\n${path}\n` +
    '把需要的文件从这里复制回原位置即可（应用不代劳放回，以免覆盖你之后放进同名位置的文件）。'
}

/**
 * 悬空链接行的说明（M290 定案后重写）。
 *
 * 改前那句是「如需恢复成独立文件，点右侧「回撤」即可（备份仍在，回撤不依赖链接是否有效）」——
 * 真机证明"备份仍在"不成立，且它恰好挂在最需要的行上。重写后仍然要说两件原话里对的事：
 * 数据没丢（只是路径替身失效）、恢复动作是**手动放回**。
 */
export function danglingKeepTitle(path: string): string {
  return '软链接已失效（悬空）：它指向的保留文件当前不可访问（可能已被删除、移动，或所在磁盘未接入）。\n' +
    '你的数据没有丢失——合并时磁盘上只保留了一份，这一条只是指向它的路径替身。\n' +
    `保留源：${path}\n` +
    '这一条不靠回撤恢复（合并前的备份在合并成功时已删除）。用右侧「直达保留原目录」打开那个文件夹，手动把文件放回原位置。'
}

/**
 * 链接类条目「去向」列的口径标注（M291，2026-09-27 实施批）。
 *
 * 为什么这一格必须自带时间戳性质的措辞：它取的是**记账那一刻**写进账本的 `linkSrc`，
 * 不是现读的链接指向。真机读数（04 §6.50 一 W3-6 同场）：手工把 `group_02` 位置上的
 * 软链接改指到同目录第三个文件之后，执行侧的 `verifySymlinked` 当场拦住（交回「标识不符」，
 * 第三方文件没被误删），而记录页那一行仍显示 `软链接 → …\keep.bin` —— 一条已被改指的链接
 * 在台账上看起来完全健康。执行侧守住、显示侧看不出来，就是这一条登记的全部原因。
 *
 * ★ 取向边界：另一条路是现读一次目标（与回撤前那道校验同源），但那要给列表每行加一次
 *   逐行 IPC；而 M291 明写不主张"改指后清扫会出错"，为显示口径付那个代价不值 ⇒ 改文案。
 */
export const RECORDED_TARGET_LABEL = '记录中的目标'

/**
 * 链接类条目（软链接/硬链接）在「去向」列的文案。
 *
 * 两档都要标注：硬链接那一格同样是记账时的事实（链接名被删掉后它也不会自己复原）。
 * 但两档的字样不得折成一个——改前视图就是靠后端的 `isSymlink` 区分的，那个标记来自
 * Lstat，比按 kind 猜可靠（M290 同一纪律）。
 */
export function recordedDest(target: string, symlink: boolean): string {
  return `${symlink ? '软链接' : '硬链接'}（${RECORDED_TARGET_LABEL}）→ ${target}`
}

/**
 * 展示判据：这一类记录**是否给用户摆「应用内回撤」这个出口**。
 *
 * 为什么由前端按 kind 判、而不是改后端的 `undoable`：`undoable` 是**落库那一刻**写进
 * 账本的字段，改判据只影响此后新记的条目，历史行会两种口径并存；而后端 `undoSymlink`
 * 本身要留着（备份残留时它是真能撤的）。⇒ 后端事实不动，界面对软链接不再摆这个出口。
 */
export function offersInAppUndo(kind: string): boolean {
  return kind !== SYMLINK_KIND
}
